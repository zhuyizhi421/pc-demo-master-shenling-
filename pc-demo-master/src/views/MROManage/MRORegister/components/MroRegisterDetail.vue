<template>
  <div class="layout-child-page-container">
    <div class="wrap">
      <div class="layout-child-page-content detail-base-content" style="flex: none">
        <div class="page-toolbar">
          <el-button plain icon="ArrowLeft" @click="emit('close')">返回</el-button>
        </div>

        <CustomTitle title="MRO 登记单详情" :is-table-title="false" show-short-bar />

        <CustomDescription
          v-if="!isBaseInfoCollapsed"
          :data="detailData || {}"
          :configs="descriptionConfig"
        >
          <template #status-content>
            <el-tag
              :type="isReviewed ? 'success' : 'danger'"
              size="small"
            >
              {{ EnumMRORegisterStatusMap[detailData?.status as EnumMRORegisterStatus] }}
            </el-tag>
          </template>
        </CustomDescription>
      </div>

      <div class="other-organ">
        <div class="organ-box" @click="isBaseInfoCollapsed = !isBaseInfoCollapsed">
          <template v-if="isBaseInfoCollapsed">
            <el-icon><DArrowRight /></el-icon>
            <span>展开</span>
          </template>
          <template v-else>
            <el-icon><DArrowLeft /></el-icon>
            <span>收起</span>
          </template>
        </div>
      </div>

      <div class="layout-child-page-content detail-tab-content">
        <el-tabs v-model="activeTab" type="border-card" class="detail-tabs custom-tabs">
          <el-tab-pane label="登记项列表" :name="DETAIL_TAB.RegisterItems" />
          <el-tab-pane label="登记结果明细" :name="DETAIL_TAB.ResultDetails" />
        </el-tabs>

        <div
          v-if="activeTab === DETAIL_TAB.RegisterItems"
          class="detail-pane custom-table-container"
        >
          <CustomTable v-model:table-data="tableData" :config="tableConfig" />
        </div>

        <div v-else class="detail-pane result-pane">
          <div class="result-toolbar">
            <span class="result-toolbar__summary">
              {{
                isReviewed
                  ? `已生成 ${resultTableData.length} 条明细`
                  : "复核后生成登记结果明细"
              }}
            </span>
            <el-button
              v-if="autoGeneratedBarcodes.length"
              type="primary"
              @click="onPrintAllClick"
            >
              打印全部
            </el-button>
          </div>

          <el-empty
            v-if="!isReviewed"
            description="复核后生成登记结果明细"
          />

          <el-empty
            v-else-if="!resultLoading && !resultTableData.length"
            description="当前登记单暂无生成结果"
          />

          <el-table
            v-else
            v-loading="resultLoading"
            :data="resultTableData"
            border
            stripe
            height="100%"
          >
            <el-table-column prop="serialNo" label="序列号" width="90" align="center" />
            <el-table-column prop="mroNo" label="MRO 编号" min-width="150" />
            <el-table-column prop="mroModelName" label="MRO 名称" min-width="170" />
            <el-table-column prop="mroSpec" label="规格" min-width="130">
              <template #default="{ row }">
                {{ row.mroSpec || "--" }}
              </template>
            </el-table-column>
            <el-table-column
              prop="barcodeHandleTypeText"
              label="标签码处理方式"
              min-width="180"
            />
            <el-table-column prop="barcode" label="标签码" min-width="180">
              <template #default="{ row }">
                {{ row.barcode || "--" }}
              </template>
            </el-table-column>
            <el-table-column prop="warehouseName" label="仓库" min-width="140">
              <template #default="{ row }">
                {{ row.warehouseName || "--" }}
              </template>
            </el-table-column>
            <el-table-column prop="warehouseLocationName" label="库位" min-width="140">
              <template #default="{ row }">
                {{ row.warehouseLocationName || "--" }}
              </template>
            </el-table-column>
            <el-table-column prop="printStatusText" label="打印状态" width="120" align="center" />
            <el-table-column prop="operation" label="操作" width="190" fixed="right" align="center">
              <template #default="{ row }">
                <el-button link type="primary" size="small" @click="onResultViewClick(row)">
                  查看台账
                </el-button>
                <el-button
                  v-if="row.isAutoGeneratedBarcode && row.barcode"
                  link
                  type="primary"
                  size="small"
                  @click="onPrintSingleClick(row)"
                >
                  补打/重打
                </el-button>
              </template>
            </el-table-column>
          </el-table>
        </div>
      </div>
    </div>

    <MroInfoDialog v-model="mroInfoVisible" :mro-id="selectedMroInfoId" />
  </div>
</template>

<script setup lang="ts">
import { queryFactoryModelList } from "@/api/fm"
import { queryMroInfoPageList } from "@/api/operation/mro/mro-info"
import CustomDescription from "@/components/CustomDescription/index.vue"
import CustomTable from "@/components/CustomTable/index.vue"
import type { ITableConfig } from "@/components/CustomTable/type"
import CustomTitle from "@/components/CustomTitle/index.vue"
import {
  EnumMROIdentityManageMap,
  EnumMRORegisterStatus,
  EnumMRORegisterStatusMap
} from "@/constant/enums"
import { FORMAT_TIME } from "@/constant/time"
import useBarcodePrint from "@/hooks/useBarcodePrint"
import type { IOption } from "@/types/common"
import type { IMroInfoPageListItem } from "@/types/maintain/mro-manage/mro-info"
import type {
  IMroRegisterItem as ITableRow,
  IMroRegisterPageListItem
} from "@/types/maintain/mro-manage/mro-register"
import { precisionConversion } from "@/utils/common"
import MroInfoDialog from "@/views/MROManage/MROInfo/components/MroInfoDialog.vue"

defineOptions({
  name: "MroRegisterDetail"
})

const DETAIL_TAB = {
  RegisterItems: "registerItems",
  ResultDetails: "resultDetails"
} as const

interface IRegisterResultRow extends IMroInfoPageListItem {
  barcodeHandleType: string
  barcodeHandleTypeText: string
  isAutoGeneratedBarcode: boolean
  mroModelName: string
  mroModelNo: string
  mroSpec: string
  printStatusText: string
  serialNo: number
}

const props = withDefaults(
  defineProps<{
    data?: IMroRegisterPageListItem
  }>(),
  {}
)
const emit = defineEmits<{
  (e: "close"): void
}>()

const { printBarcode } = useBarcodePrint()

const activeTab = ref<(typeof DETAIL_TAB)[keyof typeof DETAIL_TAB]>(DETAIL_TAB.RegisterItems)
const isBaseInfoCollapsed = ref(false)
const warehouseOptions = ref<(IOption & { code: string })[]>([])
const detailData = ref<IMroRegisterPageListItem>()
const tableData = ref<ITableRow[]>([])
const resultLoading = ref(false)
const resultSourceRows = ref<IMroInfoPageListItem[]>([])
const mroInfoVisible = ref(false)
const selectedMroInfoId = ref("")

const formatDisplayTime = (value?: string) => {
  if (!value) {
    return "--"
  }
  const target = dayjs(value)
  return target.isValid() ? target.format(FORMAT_TIME) : value
}

const isReviewed = computed(
  () => detailData.value?.status === EnumMRORegisterStatus.REVIEWED
)

const descriptionConfig = [
  {
    field: "mroRegisterNo",
    label: "登记单号："
  },
  {
    field: "mroRegisterEmpName",
    label: "登记人：",
    formatter: () => detailData.value?.mroRegisterEmpName || "--"
  },
  {
    field: "warehouseName",
    label: "仓库名称："
  },
  {
    field: "warehouseNo",
    label: "仓库编号："
  },
  {
    field: "warehouseInEntryNo",
    label: "关联入库单：",
    formatter: () => detailData.value?.warehouseInEntryNo || "--"
  },
  {
    field: "status",
    label: "状态：",
    slots: {
      content: "status-content"
    }
  },
  {
    field: "createByName",
    label: "创建人："
  },
  {
    field: "createTime",
    label: "创建日期：",
    formatter: () => formatDisplayTime(detailData.value?.createTime)
  },
  {
    field: "checkByName",
    label: "复核人：",
    formatter: () => detailData.value?.checkByName || "--"
  },
  {
    field: "completeTime",
    label: "登记完成时间：",
    formatter: () => formatDisplayTime(detailData.value?.completeTime)
  }
]

const tableConfig = ref<ITableConfig>({
  height: "100%",
  columns: [
    {
      prop: "mroModelName",
      label: "MRO 名称",
      minWidth: 160
    },
    {
      prop: "mroModelNo",
      label: "MRO 编号",
      minWidth: 160
    },
    {
      prop: "mroSpec",
      label: "规格",
      minWidth: 140
    },
    {
      prop: "mroCategoryName",
      label: "MRO 类型",
      minWidth: 160
    },
    {
      prop: "identityManage",
      label: "标识管理",
      minWidth: 120,
      align: "center",
      formatter: ({ identityManage }: { identityManage: number }) =>
        EnumMROIdentityManageMap[identityManage]
    },
    {
      prop: "registerNums",
      label: "登记数量",
      minWidth: 120,
      align: "right",
      formatter: (row: ITableRow) => precisionConversion(row.registerNums, row.decimalNumber)
    },
    {
      prop: "barcodeHandleType",
      label: "标签码处理方式",
      minWidth: 180,
      align: "center",
      formatter: (row: ITableRow) => {
        if (!row.identityManage) {
          return ""
        }
        const type =
          row.barcodeHandleType || (row.autoGenerateCode ? "system_generate" : "customer_existing")
        return type === "system_generate" ? "系统自动生成标签码" : "客户已有标签码"
      }
    },
    {
      prop: "warehouseLocationName",
      label: "库位",
      minWidth: 160,
      align: "center",
      formatter: ({ warehouseLocationName }: ITableRow) => warehouseLocationName || "--"
    },
    {
      prop: "remarks",
      label: "备注",
      minWidth: 200,
      align: "center"
    }
  ]
})

const normalizeBarcodeHandleType = (row: ITableRow) => {
  if (row.barcodeHandleType) {
    return row.barcodeHandleType
  }
  if (!row.identityManage) {
    return ""
  }
  return row.autoGenerateCode ? "system_generate" : "customer_existing"
}

const getMatchedRegisterItem = (row: IMroInfoPageListItem) => {
  const exactMatch = tableData.value.find((item) => {
    return (
      String(item.mroModelId || "") === String(row.mroModelId || "") &&
      String(item.warehouseLocationId || "") === String(row.warehouseLocationId || "") &&
      String(item.remarks || "") === String(row.remarks || "")
    )
  })
  if (exactMatch) {
    return exactMatch
  }

  const locationMatch = tableData.value.find((item) => {
    return (
      String(item.mroModelId || "") === String(row.mroModelId || "") &&
      String(item.warehouseLocationId || "") === String(row.warehouseLocationId || "")
    )
  })
  if (locationMatch) {
    return locationMatch
  }

  return tableData.value.find((item) => String(item.mroModelId || "") === String(row.mroModelId || ""))
}

const getRegisterItemOrder = (row: IMroInfoPageListItem) => {
  const exactMatchIndex = tableData.value.findIndex((item) => {
    return (
      String(item.mroModelId || "") === String(row.mroModelId || "") &&
      String(item.warehouseLocationId || "") === String(row.warehouseLocationId || "") &&
      String(item.remarks || "") === String(row.remarks || "")
    )
  })
  if (exactMatchIndex >= 0) {
    return exactMatchIndex
  }

  const locationMatchIndex = tableData.value.findIndex((item) => {
    return (
      String(item.mroModelId || "") === String(row.mroModelId || "") &&
      String(item.warehouseLocationId || "") === String(row.warehouseLocationId || "")
    )
  })
  if (locationMatchIndex >= 0) {
    return locationMatchIndex
  }

  const modelMatchIndex = tableData.value.findIndex(
    (item) => String(item.mroModelId || "") === String(row.mroModelId || "")
  )
  return modelMatchIndex >= 0 ? modelMatchIndex : Number.MAX_SAFE_INTEGER
}

const resultTableData = computed<IRegisterResultRow[]>(() => {
  const sortedRows = [...resultSourceRows.value].sort((prev, next) => {
    const prevOrder = getRegisterItemOrder(prev)
    const nextOrder = getRegisterItemOrder(next)
    if (prevOrder !== nextOrder) {
      return prevOrder - nextOrder
    }
    return String(prev.mroNo || "").localeCompare(String(next.mroNo || ""))
  })

  return sortedRows.map((row, index) => {
    const matchedRegisterItem = getMatchedRegisterItem(row)
    const barcodeHandleType = matchedRegisterItem ? normalizeBarcodeHandleType(matchedRegisterItem) : ""
    const isAutoGeneratedBarcode = barcodeHandleType === "system_generate"

    return {
      ...row,
      barcodeHandleType,
      barcodeHandleTypeText: !matchedRegisterItem
        ? "--"
        : barcodeHandleType === "system_generate"
          ? "系统自动生成标签码"
          : barcodeHandleType === "customer_existing"
            ? "客户已有标签码"
            : "未启用标识管理",
      isAutoGeneratedBarcode,
      mroModelName: row.mroModelVo?.mroModelName || "",
      mroModelNo: row.mroModelVo?.mroModelNo || "",
      mroSpec: row.mroModelVo?.mroSpec || "",
      printStatusText: isAutoGeneratedBarcode && row.barcode ? "可打印" : "--",
      serialNo: index + 1
    }
  })
})

const autoGeneratedBarcodes = computed(() =>
  resultTableData.value
    .filter((item) => item.isAutoGeneratedBarcode && item.barcode)
    .map((item) => String(item.barcode || ""))
)

const initFormData = async () => {
  detailData.value = props.data
    ? {
        ...props.data
      }
    : undefined

  const target = warehouseOptions.value.find((item) => item.value === props.data?.warehouseId)
  if (detailData.value) {
    detailData.value.warehouseNo = target?.code || detailData.value.warehouseNo || ""
  }

  tableData.value = props.data?.registerItemVos || []
  await getRegisterResultRows()
}

const getWarehouseOptions = async () => {
  const records = await queryFactoryModelList({
    isStorage: true,
    isEnable: true
  })
  warehouseOptions.value = records.map((item) => ({
    label: item.entityName,
    value: item.id,
    code: item.entityCode
  }))
}

const getRegisterResultRows = async () => {
  if (!isReviewed.value || !detailData.value?.id) {
    resultSourceRows.value = []
    return
  }

  resultLoading.value = true
  try {
    const expectedResultCount = tableData.value.reduce((count, item) => {
      return count + (item.identityManage ? Number(item.registerNums || 0) : 1)
    }, 0)
    const result = await queryMroInfoPageList({
      pageQuery: {
        pageNum: 1,
        pageSize: Math.max(expectedResultCount, 50)
      },
      queryParam: {
        registerRecordId: detailData.value.id
      }
    })
    resultSourceRows.value = result?.records || []
  } finally {
    resultLoading.value = false
  }
}

const onResultViewClick = (row: IRegisterResultRow) => {
  selectedMroInfoId.value = row.id
  mroInfoVisible.value = true
}

const onPrintAllClick = async () => {
  if (!autoGeneratedBarcodes.value.length) {
    return
  }
  await printBarcode(autoGeneratedBarcodes.value)
}

const onPrintSingleClick = async (row: IRegisterResultRow) => {
  if (!row.barcode) {
    return
  }
  await printBarcode([row.barcode])
}

onMounted(async () => {
  await getWarehouseOptions()
  await initFormData()
})

watch(
  () => props.data,
  async () => {
    await initFormData()
  }
)
</script>

